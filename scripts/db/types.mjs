import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { createDatabase, repoRoot } from "./bootstrap.mjs";

const OUTPUT = path.join(repoRoot, "src", "lib", "database.types.ts");

function quote(value) {
  return `"${value}"`;
}

function enumType(name) {
  return `Database["public"]["Enums"]["${name}"]`;
}

function scalarType(udt, enums) {
  if (enums[udt]) return enumType(udt);
  switch (udt) {
    case "uuid":
    case "text":
    case "varchar":
    case "bpchar":
    case "char":
    case "name":
    case "citext":
      return "string";
    case "int2":
    case "int4":
    case "int8":
    case "numeric":
    case "float4":
    case "float8":
    case "oid":
      return "number";
    case "bool":
      return "boolean";
    case "json":
    case "jsonb":
      return "Json";
    case "date":
    case "time":
    case "timetz":
    case "timestamp":
    case "timestamptz":
      return "string";
    default:
      return "Json";
  }
}

function columnType(column, enums) {
  const udt = column.udt_name;
  if (udt.startsWith("_")) {
    const base = udt.slice(1);
    if (enums[base]) return `${enumType(base)}[]`;
    const inner = scalarType(base, enums);
    return `${inner}[]`;
  }
  return scalarType(udt, enums);
}

function columnLine(name, type, nullable, optional) {
  const value = nullable ? `${type} | null` : type;
  return `${name}${optional ? "?" : ""}: ${value};`;
}

function renderTable(columns, enums, mode) {
  const lines = [];
  for (const column of columns) {
    const nullable = column.is_nullable === "YES";
    if (mode === "insert") {
      if (column.is_generated === "ALWAYS") continue;
      const optional = nullable || column.column_default !== null || column.is_identity === "YES";
      lines.push(columnLine(quote(column.column_name), columnType(column, enums), nullable, optional));
    } else if (mode === "update") {
      lines.push(columnLine(quote(column.column_name), columnType(column, enums), nullable, true));
    } else {
      lines.push(columnLine(quote(column.column_name), columnType(column, enums), nullable, false));
    }
  }
  return lines.map((line) => `        ${line}`).join("\n");
}

async function main() {
  const { db, migrations } = await createDatabase();

  const { rows: enumRows } = await db.query(`
    select t.typname as name, e.enumlabel as value
    from pg_type t
    join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public'
    order by t.typname, e.enumsortorder
  `);

  const enums = {};
  for (const row of enumRows) {
    (enums[row.name] ??= []).push(row.value);
  }

  const { rows: tables } = await db.query(`
    select table_name as name, table_type as kind
    from information_schema.tables
    where table_schema = 'public' and table_type in ('BASE TABLE', 'VIEW')
    order by table_name
  `);

  const { rows: columns } = await db.query(`
    select table_name, column_name, udt_name, is_nullable, column_default, is_generated, is_identity
    from information_schema.columns
    where table_schema = 'public'
    order by table_name, ordinal_position
  `);

  await db.close();

  const baseTables = tables.filter((table) => table.kind === "BASE TABLE");
  const views = tables.filter((table) => table.kind === "VIEW");

  const tableBlocks = baseTables.map((table) => {
    const cols = columns.filter((column) => column.table_name === table.name);
    return `      ${table.name}: {
        Row: {
${renderTable(cols, enums, "row")}
        };
        Insert: {
${renderTable(cols, enums, "insert")}
        };
        Update: {
${renderTable(cols, enums, "update")}
        };
      };`;
  });

  const viewBlocks = views.map((view) => {
    const cols = columns.filter((column) => column.table_name === view.name);
    return `      ${view.name}: {
        Row: {
${renderTable(cols, enums, "row")}
        };
        Relationships: [];
      };`;
  });

  const enumBlocks = Object.entries(enums).map(
    ([name, values]) => `      ${name}: ${values.map((value) => quote(value)).join(" | ")};`,
  );

  const output = `// Generated by scripts/db/types.mjs from supabase/migrations. Do not edit by hand.
// Run \`bun run db:types\` to regenerate after changing the schema.

export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[];

export type Database = {
  public: {
    Tables: {
${tableBlocks.join("\n")}
    };
    Views: {
${viewBlocks.join("\n")}
    };
    Functions: {};
    Enums: {
${enumBlocks.join("\n")}
    };
    CompositeTypes: {};
  };
};

type PublicSchema = Database["public"];

export type Tables<T extends keyof PublicSchema["Tables"]> =
  PublicSchema["Tables"][T]["Row"];
export type TablesInsert<T extends keyof PublicSchema["Tables"]> =
  PublicSchema["Tables"][T]["Insert"];
export type TablesUpdate<T extends keyof PublicSchema["Tables"]> =
  PublicSchema["Tables"][T]["Update"];
export type Enums<T extends keyof PublicSchema["Enums"]> = PublicSchema["Enums"][T];
`;

  await mkdir(path.dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, output, "utf8");
  console.log(
    `db:types wrote ${path.relative(repoRoot, OUTPUT)} (${migrations.length} migrations, ${baseTables.length} tables, ${views.length} views, ${Object.keys(enums).length} enums)`,
  );
}

main().catch((error) => {
  console.error(`db:types failed: ${error.message}`);
  process.exit(1);
});
